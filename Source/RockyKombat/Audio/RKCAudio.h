// RKCAudio.h
//
// Rocky Kombat - the presentation audio layer.
//
// RESPONSIBILITY: turn simulation events into sounds, and nothing else. Audio
// never feeds back into RKC::FCombatSim: the director drains the simulation's
// event queue and hands each event here, exactly as it hands presentation state
// to ARKCFighter. A missing sound asset therefore degrades the experience but
// can never change a match result.
//
// TWO STAGES, ON PURPOSE:
//   1. PlanEvent()  - pure: it decides WHICH sound an event should make and
//                     returns that decision as a name. No engine state, no
//                     playback, no side effects, so a test can assert the
//                     decisions without an audio device.
//   2. PlayEvent()  - takes that plan and issues it, applying the player's
//                     volume settings and the one-sound-per-event guarantee.
// Tests read step 1; the game calls step 2; the evidence record reports both.
//
// ONE SOUND PER EVENT: every simulation event maps to at most one impact/utility
// sound plus at most one voice line, and PlayEvent() refuses a second identical
// (tick, sound) pair. That is the anti-double-fire guarantee at the audio layer,
// matching the edge-triggered guarantee the input layer already gives.
//
// ASSETS: two layers, and they are never confused with each other.
//   * The synthetic layer: original procedural synthesis generated by
//     Tools/Audio/rkc_generate_audio.py into Content/RockyKombat/Audio. It is
//     generated code, not a recording, and it is never described as a real
//     voice.
//   * The recorded layer: real human performances cut from a CC0 Freesound take
//     by Tools/Audio/rkc_slice_freesound.py into
//     Content/RockyKombat/Audio/Recorded. This is a genuine recorded voice.
// The catalog below is the authoritative list of both, and it is resolved - not
// assumed - at startup; whatever is missing is reported by name rather than
// silently skipped, and a missing recorded take falls back to the synthetic
// voice with the substitution counted, not hidden.
//
// No audio from any commercial fighting game is used here.

